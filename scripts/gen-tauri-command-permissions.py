#!/usr/bin/env python3
"""Generate src-tauri/permissions/*.toml from generate_handler! in lib.rs."""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / "src-tauri" / "src" / "lib.rs"
PERM_DIR = ROOT / "src-tauri" / "permissions"
ALLOWLIST = ROOT / "scripts" / "tauri-command-groups.allowlist"

SECONDARY = {
    "render_ui_surface_html",
    "open_ui_surface",
    "close_ui_surface",
    "ui_surface_event",
}


def kebab(name: str) -> str:
    return name.replace("_", "-")


def main() -> int:
    text = LIB.read_text()
    match = re.search(r"generate_handler!\[(.*?)\]", text, re.S)
    if not match:
        print("generate_handler! not found", file=sys.stderr)
        return 1

    by_mod: dict[str, list[str]] = defaultdict(list)
    for line in match.group(1).splitlines():
        line = line.strip().rstrip(",")
        if not line or line.startswith("//"):
            continue
        parts = line.split("::")
        name = parts[-1]
        if "ui_host" in line:
            mod = "ui_host"
        elif parts[0] == "commands" and len(parts) >= 3:
            mod = parts[1]
        else:
            mod = parts[0]
        by_mod[mod].append(name)

    PERM_DIR.mkdir(parents=True, exist_ok=True)
    # Remove previously generated group files (keep nothing stale).
    for path in PERM_DIR.glob("*.toml"):
        path.unlink()

    set_ids: list[str] = []
    for mod, cmds in sorted(by_mod.items()):
        cmds = sorted(set(cmds))
        blocks: list[str] = []
        for cmd in cmds:
            blocks.append(
                f'[[permission]]\n'
                f'identifier = "allow-{kebab(cmd)}"\n'
                f'description = "Allow {cmd}"\n'
                f'commands.allow = ["{cmd}"]\n'
            )
        allows = "\n".join(f'  "allow-{kebab(c)}",' for c in cmds)
        blocks.append(
            f'[[set]]\n'
            f'identifier = "group-{kebab(mod)}"\n'
            f'description = "Command group: {mod}"\n'
            f'permissions = [\n{allows}\n]\n'
        )
        (PERM_DIR / f"{mod}.toml").write_text("\n".join(blocks))
        set_ids.append(f"group-{kebab(mod)}")

    agg = "\n".join(f'  "{s}",' for s in set_ids)
    (PERM_DIR / "main-all.toml").write_text(
        "[[set]]\n"
        'identifier = "main-all-commands"\n'
        'description = "All Scribe app commands for the main window (IPC ACL baseline)"\n'
        "permissions = [\n"
        f"{agg}\n"
        "]\n"
    )

    sec_refs = "\n".join(f'  "allow-{kebab(c)}",' for c in sorted(SECONDARY))
    (PERM_DIR / "secondary.toml").write_text(
        "[[set]]\n"
        'identifier = "secondary-window"\n'
        "description = \"Minimal commands for pdf-export / scribe-ui secondary windows\"\n"
        "permissions = [\n"
        f"{sec_refs}\n"
        "]\n"
    )

    lines = [
        "# Auto-generated by scripts/gen-tauri-command-permissions.py — do not edit by hand\n"
    ]
    for mod, cmds in sorted(by_mod.items()):
        for cmd in sorted(set(cmds)):
            lines.append(f"{mod}\t{cmd}\n")
    ALLOWLIST.write_text("".join(lines))

    total = sum(len(set(v)) for v in by_mod.values())
    print(f"Wrote {len(set_ids)} groups, {total} commands → {PERM_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
